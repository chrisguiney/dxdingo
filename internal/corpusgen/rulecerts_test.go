var slugRE = regexp.MustCompile(`[^a-z0-9]+`)

func TestGenerateRuleCertsCorpus(t *testing.T) {
	var entries []entry
	for _, c := range cf.Cases() {
		entries = append(entries, certEntry(c))
	}
	entries = append(entries, mainnetWithdrawalEntries(t)...)
	writeCorpus(t, "", entries)
	writeCertsHaskellData(t)
}

func certEntry(c cf.Case) entry {
	ctx, pp, st := cf.Env()
	if c.PV != 0 {
		ctx.ProtocolVersion.Major = c.PV
		pp.ProtocolVersion.Major = c.PV
	}
	if c.Mutate != nil {
		c.Mutate(st)
	}
	tx := cf.Tx(c.Certs, c.Withdrawals)
	call := &v1.Call{}
	fn := map[string]string{"deleg": "rule_deleg", "pool": "rule_pool", "gov": "rule_gov_cert", "certs": "rule_certs"}[c.Rule]
	switch c.Rule {
	case "deleg":
		call.Request = &v1.Call_RuleDeleg{RuleDeleg: &v1.RuleDelegRequest{Context: ctx, Pparams: pp, State: st, Tx: tx, CertIndex: c.CertIndex}}
	case "pool":
		call.Request = &v1.Call_RulePool{RulePool: &v1.RulePoolRequest{Context: ctx, Pparams: pp, State: st, Tx: tx, CertIndex: c.CertIndex}}
	case "gov":
		call.Request = &v1.Call_RuleGovCert{RuleGovCert: &v1.RuleGovCertRequest{Context: ctx, Pparams: pp, State: st, Tx: tx, CertIndex: c.CertIndex}}
	case "certs":
		call.Request = &v1.Call_RuleCerts{RuleCerts: &v1.RuleCertsRequest{Context: ctx, Pparams: pp, State: st, Tx: tx}}
	}
	slug := strings.Trim(slugRE.ReplaceAllString(strings.ToLower(strings.TrimPrefix(c.Name, c.Rule+" ")), "_"), "_")
	name := fn + "_" + slug
	if len(c.Want) == 0 {
		return entry{name, c.Name + ": accepted; the delta is compared field by field", call}
	}
	return entry{name, c.Name + ": rejected with " + strings.Join(c.Want, ", "), call}
}

// writeCertsHaskellData writes the scenarios as a Haskell module so
// test/Test/RuleCerts.hs runs the same transactions against the reference.
func writeCertsHaskellData(t *testing.T) {
	var b strings.Builder
	b.WriteString("-- | Generated by internal/corpusgen TestGenerateRuleCertsCorpus: the shared\n")
	b.WriteString("-- certificate-rule scenarios as (name, rule, cert_index, protocol major,\n")
	b.WriteString("-- transaction hex, expected failures, expected delta digest).\n")
	b.WriteString("module Test.RuleCertsData (scenarios) where\n\n")
	b.WriteString("scenarios :: [(String, String, Maybe Int, Word, String, [String], String)]\n")
	b.WriteString("scenarios =\n")
	for i, c := range cf.Cases() {
		pv := c.PV
		if pv == 0 {
			pv = 10
		}
		idx := "Nothing"
		if c.CertIndex != nil {
			idx = fmt.Sprintf("Just %d", *c.CertIndex)
		}
		want := make([]string, len(c.Want))
		for j, w := range c.Want {
			want[j] = fmt.Sprintf("%q", w)
		}
		sep := "["
		if i > 0 {
			sep = ","
		}
		fmt.Fprintf(&b, "  %s (%q, %q, %s, %d, %q, [%s], %q)\n", sep, c.Name, c.Rule, idx, pv,
			hex.EncodeToString(cf.Tx(c.Certs, c.Withdrawals)), strings.Join(want, ", "), c.Delta)
	}
	b.WriteString("  ]\n")
	if err := os.WriteFile(filepath.Join("..", "..", "haskell", "dxnode-hs", "test", "Test", "RuleCertsData.hs"), []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

// mainnetWithdrawalEntries runs the withdrawal-carrying transactions of the
// mainnet Conway block through CERTS with an account table built for each:
// the account holds exactly the withdrawn amount (accepted), one more
// (the withdrawal does not drain it) or is missing (unregistered account).
func mainnetWithdrawalEntries(t *testing.T) []entry {
	txs, err := rulefixture.BlockTxs(v1.Era_ERA_CONWAY)
	if err != nil {
		t.Fatal(err)
	}
	var out []entry
	for i, raw := range txs {
		tx, err := ledger.NewTransactionFromCbor(ledger.TxTypeConway, raw)
		if err != nil || len(tx.Withdrawals()) == 0 || len(tx.Certificates()) != 0 {
			continue
		}
		type variant struct {
			name, why string
			extra     uint64
			missing   bool
		}
		for _, v := range []variant{
			{"drained", "the account holds exactly the withdrawn amount", 0, false},
			{"not_drained", "the account holds one lovelace more than the withdrawal", 1, false},
			{"unregistered", "the withdrawn account is not registered", 0, true},
		} {
			ctx, pp, _ := cf.Env()
			st := &v1.LedgerState{}
			for addr, amount := range tx.Withdrawals() {
				cred, err := addr.RewardAccountCredential()
				if err != nil {
					t.Fatal(err)
				}
				if v.missing {
					continue
				}
				kind := v1.CredentialKind_CREDENTIAL_KIND_KEY
				if cred.CredType == 1 {
					kind = v1.CredentialKind_CREDENTIAL_KIND_SCRIPT
				}
				st.Accounts = append(st.Accounts, &v1.Account{
					Credential: &v1.Credential{Kind: kind, Hash: cred.Credential.Bytes()},
					Deposit:    2_000_000,
					Balance:    amount.Uint64() + v.extra,
				})
			}
			call := &v1.Call{Request: &v1.Call_RuleCerts{RuleCerts: &v1.RuleCertsRequest{Context: ctx, Pparams: pp, State: st, Tx: raw}}}
			out = append(out, entry{
				fmt.Sprintf("rule_certs_mainnet_conway_tx%d_%s", i, v.name),
				fmt.Sprintf("tx %d of the conway mainnet block withdraws from one account: %s", i, v.why),
				call,
			})
		}
	}
	return out
}
