var ledgerSlugRE = regexp.MustCompile(`[^a-z0-9]+`)

func ledgerEntries(sc []lf.Scenario) []entry {
	var out []entry
	for _, s := range sc {
		_, rest, _ := strings.Cut(s.Name, " ")
		name := s.Fn + "_" + strings.Trim(ledgerSlugRE.ReplaceAllString(strings.ToLower(rest), "_"), "_")
		why := s.Name + ": accepted; the delta is compared field by field"
		if len(s.Want) > 0 {
			why = s.Name + ": rejected with " + strings.Join(s.Want, ", ")
		}
		out = append(out, entry{name, why, s.Call})
	}
	return out
}

func TestGenerateRuleLedgerCorpus(t *testing.T) {
	writeCorpus(t, "", append(append(ledgerEntries(lf.Scenarios()), ledgerMainnetEntries(t, false)...), ledgerLegacyMainnetEntries(t, false)...))
	writeCorpus(t, "divergences", append(append(ledgerEntries(lf.Divergences()), ledgerMainnetEntries(t, true)...), ledgerLegacyMainnetEntries(t, true)...))
	writeLedgerHaskellData(t, append(append(lf.Scenarios(), lf.BlockScenarios()...), lf.LegacyScenarios()...), lf.BlockDivergenceScenarios(), ledgerLegacyDivergenceScenarios(t))
}

// writeLedgerHaskellData writes the scenarios as a Haskell module so
// test/Test/RuleLedger.hs runs the same calls against the reference.
func writeLedgerHaskellData(t *testing.T, sc, div, legacyDiv []lf.Scenario) {
	var b strings.Builder
	b.WriteString("-- | Generated by internal/corpusgen TestGenerateRuleLedgerCorpus: the shared\n")
	b.WriteString("-- composed-rule scenarios as (name, function, Call as protobuf hex, expected\n")
	b.WriteString("-- failures, expected delta digest), and the scenarios on which dxnode-go\n")
	b.WriteString("-- differs, with the reference's answer.\n")
	b.WriteString("module Test.RuleLedgerData (scenarios, divergenceScenarios, legacyDivergenceScenarios) where\n\n")
	for _, list := range []struct {
		name string
		sc   []lf.Scenario
	}{{"scenarios", sc}, {"divergenceScenarios", div}, {"legacyDivergenceScenarios", legacyDiv}} {
		fmt.Fprintf(&b, "%s :: [(String, String, String, [String], String)]\n%s =\n", list.name, list.name)
		for i, s := range list.sc {
			raw, err := proto.Marshal(s.Call)
			if err != nil {
				t.Fatal(err)
			}
			want := make([]string, len(s.Want))
			for j, w := range s.Want {
				want[j] = fmt.Sprintf("%q", w)
			}
			sep := "["
			if i > 0 {
				sep = ","
			}
			fmt.Fprintf(&b, "  %s (%q, %q, %q, [%s], %q)\n", sep, s.Name, s.Fn, hex.EncodeToString(raw), strings.Join(want, ", "), s.Delta)
		}
		if len(list.sc) == 0 {
			b.WriteString("  []\n")
		} else {
			b.WriteString("  ]\n")
		}
		b.WriteString("\n")
	}
	if err := os.WriteFile(filepath.Join("..", "..", "haskell", "dxnode-hs", "test", "Test", "RuleLedgerData.hs"), []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

// ledgerMainnetEntries runs real mainnet Conway transactions through LEDGER
// over synthesised state, with the mutations the UTXO corpus uses.
func ledgerMainnetEntries(t *testing.T, divergent bool) []entry {
	var out []entry
	for i, base := range ruleBases(t, v1.Era_ERA_CONWAY, 3) {
		for _, m := range ruleMutations() {
			// An unresolved input makes gouroboros' required-redeemers rule fail
			// where the reference skips it (TestDivergenceRequiredRedeemersFailsOnUnresolvedInput).
			if (m.name == "bad_inputs") != divergent {
				continue
			}
			b := base.clone()
			m.apply(&b)
			req := &v1.RuleLedgerRequest{Context: b.ctx, Globals: b.g, Pparams: b.pp, State: b.st, Tx: b.tx}
			out = append(out, entry{
				fmt.Sprintf("rule_ledger_mainnet_conway_tx%d_%s", i, m.name),
				fmt.Sprintf("ledger tx %d of the conway mainnet block: %s", i, m.why),
				&v1.Call{Request: &v1.Call_RuleLedger{RuleLedger: req}},
			})
		}
	}
	return out
}

// ledgerLegacyDivergent names the Shelley-to-Babbage mainnet cases kept out of
// corpus/ because the nodes disagree. Three causes:
//   - an unresolved input (the bad_inputs cases of Babbage and of the scripted
//     Alonzo transaction): gouroboros' required-redeemers rule fails on it where
//     the reference skips unresolved inputs (the same cause as
//     TestDivergenceRequiredRedeemersFailsOnUnresolvedInput; for Babbage
//     TestDivergenceLegacyRequiredRedeemersFailsOnUnresolvedInput);
//   - a spending redeemer for a key-locked input with no Plutus script: the
//     synthesised state locks every input with a key, so the Babbage
//     transaction whose scripts come from reference inputs reaches it (the
//     cause of the rule_utxow_babbage_scripted2 divergences);
//   - the first Babbage transaction creates an output whose asset names are in
//     canonical CBOR order (shortest first), which Dingo stores as the
//     transaction wrote it and the reference re-encodes in byte order
//     (TestDivergenceLegacyLedgerKeepsWireBytesOfCreatedOutputs).
var ledgerLegacyDivergent = func() map[string]bool {
	out := map[string]bool{
		"rule_ledger_mainnet_babbage_tx0_valid":            true,
		"rule_ledger_mainnet_alonzo_scripted0_bad_inputs":  true,
		"rule_ledger_mainnet_babbage_scripted0_bad_inputs": true,
		"rule_ledger_mainnet_babbage_scripted1_bad_inputs": true,
	}
	for i := 0; i < 3; i++ {
		out[fmt.Sprintf("rule_ledger_mainnet_babbage_tx%d_bad_inputs", i)] = true
	}
	for _, m := range ruleMutations() {
		out["rule_ledger_mainnet_babbage_scripted2_"+m.name] = true
	}
	return out
}()

// ledgerLegacyMainnetEntries runs real mainnet transactions of Shelley to
// Babbage through LEDGER over synthesised state, with the mutations the UTXO
// corpus uses. The plain family needs nothing beyond key witnesses; the
// scripted family adds native scripts, minting, collateral, reference inputs
// and Plutus data.
func ledgerLegacyMainnetEntries(t *testing.T, divergent bool) []entry {
	var out []entry
	for _, family := range []struct {
		name     string
		eligible func(v1.Era, []byte) bool
	}{
		{"tx", rulefixture.Plain},
		{"scripted", rulefixture.Scripted},
	} {
		for _, era := range []v1.Era{v1.Era_ERA_SHELLEY, v1.Era_ERA_ALLEGRA, v1.Era_ERA_MARY, v1.Era_ERA_ALONZO, v1.Era_ERA_BABBAGE} {
			eraName := strings.ToLower(strings.TrimPrefix(era.String(), "ERA_"))
			for i, base := range ruleBasesFor(t, era, 3, family.eligible) {
				for _, m := range ruleMutations() {
					name := fmt.Sprintf("rule_ledger_mainnet_%s_%s%d_%s", eraName, family.name, i, m.name)
					if ledgerLegacyDivergent[name] != divergent {
						continue
					}
					b := base.clone()
					m.apply(&b)
					req := &v1.RuleLedgerRequest{Context: b.ctx, Globals: b.g, Pparams: b.pp, State: b.st, Tx: b.tx}
					out = append(out, entry{
						name,
						fmt.Sprintf("ledger %s %d of the %s mainnet block: %s", family.name, i, eraName, m.why),
						&v1.Call{Request: &v1.Call_RuleLedger{RuleLedger: req}},
					})
				}
			}
		}
	}
	return out
}

// ledgerLegacyDivergenceScenarios are the mainnet Babbage LEDGER cases on which
// dxnode-go differs, with the reference's answer: the Haskell tests run them
// through the reference's rule and, for the unresolved input, through the
// LEDGER rule alone.
func ledgerLegacyDivergenceScenarios(t *testing.T) []lf.Scenario {
	t.Helper()
	out := ledgerLegacyBlockDivergences(t)
	for _, e := range ledgerLegacyMainnetEntries(t, true) {
		call := e.call
		switch e.name {
		case "rule_ledger_mainnet_babbage_tx0_bad_inputs":
			out = append(out, lf.Scenario{
				Name: e.name, Fn: "rule_ledger", Call: call,
				Want: []string{"UTXO/BadInputsUTxO", "UTXO/ValueNotConservedUTxO"},
			})
		case "rule_ledger_mainnet_babbage_tx0_valid":
			tx, err := ledger.NewTransactionFromCbor(ledger.TxTypeBabbage, call.GetRuleLedger().GetTx())
			if err != nil {
				t.Fatal(err)
			}
			out = append(out, lf.Scenario{
				Name: e.name, Fn: "rule_ledger", Call: call,
				Delta: fmt.Sprintf("U+=%d U-=%d fee=%d", len(tx.Outputs()), len(tx.Inputs()), tx.Fee().Uint64()),
			})
		}
	}
	return out
}

